"""WAF fingerprinting in _build_target_profile (detect_waf)."""
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from xploit.reporting import render_text_report
from xploit.scanner import WebScanner, detect_waf


class _Resp:
    """Minimal requests.Response stand-in (mirrors tests/test_stage1_smart.py)."""
    def __init__(self, text="", status_code=200, headers=None, url="http://x/"):
        self.text = text
        self.status_code = status_code
        self.headers = headers or {}
        self.url = url


def _scanner_with_pages(pages):
    sc = WebScanner("http://x/", mode="passive", depth=0, max_pages=16)
    sc.root = "http://x/"
    sc.pages = pages
    sc.forms = []
    return sc


# --- detect_waf unit tests ----------------------------------------------

def test_empty_headers_and_body():
    assert detect_waf({}, "") == ([], [])
    assert detect_waf(None) == ([], [])


def test_cloudflare_header():
    vendors, signals = detect_waf({"CF-Ray": "abc123"})
    assert vendors == ["Cloudflare"]
    assert signals == ["cf-ray header present"]


def test_cloudflare_server_header():
    vendors, signals = detect_waf({"Server": "cloudflare"})
    assert vendors == ["Cloudflare"]
    assert signals == ["Server: cloudflare"]


def test_cloudflare_cookie():
    vendors, signals = detect_waf(
        {"Set-Cookie": "__cfduid=d123; expires=Thu, 01-Jan-1970 00:00:01 GMT"})
    assert vendors == ["Cloudflare"]
    assert "Set-Cookie: __cfduid" in signals


def test_akamai_headers():
    vendors, signals = detect_waf({
        "X-Akamai-Transformed": "9",
        "Server": "AkamaiGHost",
    })
    assert vendors == ["Akamai"]
    assert "x-akamai-transformed header present" in signals
    assert "Server: AkamaiGHost" in signals


def test_sucuri_and_imperva_headers():
    vendors, _ = detect_waf({"X-Sucuri-ID": "1201"})
    assert vendors == ["Sucuri"]
    vendors, _ = detect_waf({"X-CDN": "Imperva"})
    assert vendors == ["Imperva"]
    vendors, signals = detect_waf({"Set-Cookie": "incap_ses_1=abc; visid_incap_2=def"})
    assert vendors == ["Imperva"]
    assert "Set-Cookie: incap_ses_" in signals


def test_f5_server_header():
    vendors, _ = detect_waf({"Server": "BigIP"})
    assert vendors == ["F5 BIG-IP"]


def test_block_page_markers_only_on_error_status():
    body = "Attention Required! | Cloudflare\nCloudflare Ray ID: 123"
    vendors, _ = detect_waf({}, body, status_code=403)
    assert vendors == ["Cloudflare"]
    # The same text on a 200 page (e.g. a blog post quoting a block
    # page) must not fingerprint as protected.
    assert detect_waf({}, body, status_code=200) == ([], [])


def test_modsecurity_and_f5_block_pages():
    vendors, _ = detect_waf(
        {}, "This error was generated by ModSecurity", status_code=403)
    assert vendors == ["ModSecurity"]
    vendors, _ = detect_waf(
        {}, "The requested URL was rejected. Please consult with your "
            "administrator.", status_code=403)
    assert vendors == ["F5 BIG-IP"]


def test_multiple_vendors_sorted_and_signals_deduped():
    vendors, signals = detect_waf({
        "CF-Ray": "1",
        "Server": "cloudflare",
        "X-Sucuri-ID": "1201",
        "CF-Cache-Status": "HIT",
    })
    assert vendors == ["Cloudflare", "Sucuri"]
    assert len(signals) == len(set(signals))


def test_plain_headers_do_not_false_positive():
    vendors, signals = detect_waf(
        {"Server": "Apache/2.4", "X-Powered-By": "PHP/8.1"},
        "Access denied. Please try again later.", status_code=403)
    assert vendors == []
    assert signals == []


# --- profile integration -------------------------------------------------

def test_profile_records_waf_from_headers():
    sc = _scanner_with_pages({
        "http://x/": _Resp(headers={
            "Content-Type": "text/html",
            "Server": "cloudflare",
            "CF-Ray": "abc",
        }),
    })
    sc._build_target_profile()
    assert sc.target_profile["waf"] == ["Cloudflare"]
    assert "cf-ray header present" in sc.target_profile["waf_signals"]
    assert "Server: cloudflare" in sc.target_profile["waf_signals"]


def test_profile_records_waf_from_block_page_body():
    sc = _scanner_with_pages({
        "http://x/": _Resp(
            text="<html><title>Attention Required! | Cloudflare</title></html>",
            status_code=403,
            headers={"Content-Type": "text/html"},
        ),
    })
    sc._build_target_profile()
    assert sc.target_profile["waf"] == ["Cloudflare"]
    assert any("block page" in s for s in sc.target_profile["waf_signals"])


def test_profile_waf_empty_for_plain_target():
    sc = _scanner_with_pages({
        "http://x/": _Resp(headers={
            "Content-Type": "text/html", "Server": "Apache/2.4",
        }),
    })
    sc._build_target_profile()
    assert sc.target_profile["waf"] == []
    assert sc.target_profile["waf_signals"] == []


def test_profile_waf_dedupes_across_pages():
    sc = _scanner_with_pages({
        "http://x/": _Resp(headers={"CF-Ray": "1"}),
        "http://x/about": _Resp(headers={"CF-Ray": "2"}),
    })
    sc._build_target_profile()
    assert sc.target_profile["waf"] == ["Cloudflare"]
    assert sc.target_profile["waf_signals"].count("cf-ray header present") == 1


def test_text_report_names_waf_in_coverage_line():
    sc = _scanner_with_pages({
        "http://x/": _Resp(headers={"CF-Ray": "1"}),
    })
    sc._build_target_profile()
    from xploit.scanner import ScanResult
    result = ScanResult(
        target="http://x/", normalized_target="http://x/",
        started_at="", duration_seconds=0.0, status="completed",
        scan_mode="passive", scope_prefix="/", completion_percent=100,
        checks_run=[], pages_seen=["http://x/"], forms_seen=0,
        findings=[], errors=[], target_profile=sc.target_profile,
    )
    assert "WAF: Cloudflare" in render_text_report(result, colors=False)


# --- live fixture: header marker end to end -------------------------------

class _Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):  # silence test output
        pass

    def do_GET(self):
        body = b"home page"
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("CF-Ray", "test-ray-id")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def test_live_scan_profiles_cloudflare_header():
    server = ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        base_url = f"http://127.0.0.1:{server.server_address[1]}/"
        result = WebScanner(
            base_url, mode="passive", modules="general", timeout=5,
        ).scan()
        assert result.status == "completed"
        assert result.target_profile["waf"] == ["Cloudflare"]
        assert "WAF: Cloudflare" in render_text_report(result, colors=False)
    finally:
        server.shutdown()
        server.server_close()
